function t(key, vars) {
  const lang = document.documentElement.lang || "en";
  let str = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
  if (vars) {
    Object.keys(vars).forEach(k => { str = str.replace(`{${k}}`, vars[k]); });
  }
  return str;
}

function applyLanguage(lang) {
  document.documentElement.lang = lang;
  localStorage.setItem("rialo_lang", lang);

  // innerHTML on purpose: some strings (e.g. the hero title) contain a <br/>.
  // All translation strings are static and author-controlled, so this is safe.
  document.querySelectorAll("[data-i18n]").forEach(el => {
    el.innerHTML = t(el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  // dynamic content that isn't covered by static data-i18n strings
  if (typeof updateProfileButtonLabel === "function") updateProfileButtonLabel();
  if (typeof renderIdentities === "function") renderIdentities();
  if (typeof renderCommunities === "function") renderCommunities();
  if (typeof refreshRialoBalanceLabel === "function") refreshRialoBalanceLabel();
}
